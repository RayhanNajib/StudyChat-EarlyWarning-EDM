def get_data_dictionary() -> pd.DataFrame:
    """Returns a clean dataframe representation of the codebook for UI rendering."""
    records = []
    for col, meta in CODEBOOK_REGISTRY.items():
        records.append({
            "Nama Kolom": col,
            "Label Deskriptif": meta["label"],
            "Tipe Data": meta["type"],
            "Peran dalam Pipeline": meta["role"],
            "Status Kebocoran": "Leakage (Dikeluarkan)" if meta["leakage"] else "Aman (Diizinkan)",
            "Deskripsi Ilmiah": meta["description"],
            "Contoh Nilai": meta["example"]
        })
    return pd.DataFrame(records)
